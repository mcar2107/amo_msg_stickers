import type { RecentRec } from '@core/db.types';
import type { ManifestRecent } from '@core/libraryFile';

/**
 * Итог слияния недавних файла с недавними библиотеки.
 */
export type RecentMerge = {
  /**
   * Записи из файла, которые встают в недавние: нового элемента или более поздней отправки, в пределах лимита вида.
   * Запись с ключом, который в недавних уже есть, заменяет прежнюю.
   */
  put: RecentRec[];

  /**
   * Ключи недавних библиотеки, которые после слияния выходят за лимит своего вида, — в том числе ключ, время которого
   * файл сделал более поздним, но недостаточно поздним для лимита.
   */
  deleteKeys: string[];

  /**
   * Элементы файла, которые попадут в недавние, — те же, что в `put`, в виде описания файла.
   */
  added: ManifestRecent[];
};
