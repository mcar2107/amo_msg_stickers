import type { FavoriteRec, Pack, RecentRec, StickerRec } from '@core/db.types';

/**
 * Состояние библиотеки в момент записи импорта — то, что транзакция прочитала перед записью.
 */
export type ImportLibrary = {
  /**
   * Id паков, которые есть в библиотеке.
   */
  packIds: Set<string>;

  /**
   * Id всех стикеров библиотеки, в любом паке.
   */
  stickerIds: Set<string>;

  /**
   * Наибольшее время добавления стикеров пака в библиотеке по id пака. Нет ключа — у пака в библиотеке нет стикеров.
   */
  lastStickerAt: Map<string, number>;

  /**
   * Ключи избранного библиотеки.
   */
  favoriteKeys: Set<string>;

  /**
   * Недавние библиотеки обоих видов в любом порядке.
   */
  recent: readonly RecentRec[];

  /**
   * Записи стикеров библиотеки по id — тех, на которые ссылается избранное плана. Нет ключа — такого стикера в
   * библиотеке нет.
   */
  favoriteStickers: Map<string, StickerRec>;
};

/**
 * Параметры построения записей импорта.
 */
export type ImportRecordsOptions = {
  /**
   * Время начала записи (мс): время добавления нового пака без него в файле и отсчёт стикеров нового пака.
   */
  startedAt: number;

  /**
   * Запись «Моих стикеров» той же формы, что создаёт пикер, — пишется, если своего пака в библиотеке нет.
   */
  customPack: Pack;
};

/**
 * Что импорт записал на самом деле.
 */
export type ImportWritten = {
  /**
   * Паки, в которые добавлен хоть один стикер, в порядке файла: и созданные, и дополненные.
   */
  packIds: string[];

  /**
   * Сколько стикеров добавлено всего.
   */
  stickerCount: number;

  /**
   * Сколько элементов добавлено в избранное, стикеров и GIF.
   */
  favoriteCount: number;

  /**
   * Сколько элементов добавлено в недавние или поднято в них более поздним временем, стикеров и GIF.
   */
  recentCount: number;

  /**
   * В избранное добавлен хоть один стикер, а не только GIF: лента стикеров получила новое в «Избранном».
   */
  hasFavoriteStickers: boolean;

  /**
   * В недавние добавлен или поднят хоть один стикер, а не только GIF.
   */
  hasRecentStickers: boolean;
};

/**
 * Записи, которые импорт кладёт в базу, и итог для статуса.
 */
export type ImportRecords = {
  /**
   * Записи новых паков; пак, который уже есть, сюда не попадает.
   */
  packs: Pack[];

  /**
   * Записи новых стикеров.
   */
  stickers: StickerRec[];

  /**
   * Записи избранного для ключей, которых в избранном нет.
   */
  favorites: FavoriteRec[];

  /**
   * Записи недавних из файла: новые и с более поздним временем, в пределах лимита вида. Запись с ключом, который в
   * недавних есть, заменяет прежнюю.
   */
  recent: RecentRec[];

  /**
   * Ключи недавних библиотеки, которые после слияния выходят за лимит своего вида.
   */
  recentDeleteKeys: string[];

  /**
   * Итог записи.
   */
  written: ImportWritten;
};
