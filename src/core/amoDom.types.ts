import type { MarkableNode } from './pageClient.types';

/**
 * Узел, видимость которого amo переключает, не размонтируя его: прежняя разметка — классом
 * `opacity-100`, стабильная — атрибутом `data-visible`.
 */
export type ShownNode = {
  /**
   * Классы узла: по ним видимость читает прежняя разметка.
   */
  classList: Pick<DOMTokenList, 'contains'>;

  /**
   * Проверка атрибута: по ней видимость читает стабильная разметка.
   */
  hasAttribute: (name: string) => boolean;
};

/**
 * Кнопка «Отправить», которую можно нажать.
 */
export type SendButton = Pick<HTMLElement, 'click'>;

/**
 * Часть разметки, которую спрашивает отправка: состояние черновика читается в момент вызова и
 * признаком той разметки, в которой поле найдено, — кнопки одной версии amo не проверяются
 * признаком другой.
 */
export type ComposeMarkup = {
  /**
   * Идёт ли редактирование отправленного сообщения.
   */
  isEditing: (composer: SendComposer) => boolean;

  /**
   * Пуст ли черновик: в поле нет ни текста, ни вложений.
   */
  isDraftEmpty: (composer: SendComposer) => boolean;

  /**
   * Кнопка «Отправить», если она сейчас показана и её можно нажать; null — её нет. Кнопка
   * может появиться позже вложения: непустой черновик ещё не значит, что отправлять можно.
   */
  sendButtonOf: (composer: SendComposer) => SendButton | null;
};

/**
 * Где встаёт попап: `composer` — от контейнера поля ввода с `transform`, `button` — от обёртки
 * кнопки стикеров.
 */
export type ButtonAnchor = 'composer' | 'button';

/**
 * Кнопка стикеров в одной разметке amo: классы повторяют кнопку эмодзи этой разметки, и стили
 * страницы применяются к ней без своего CSS.
 */
export type ButtonMarkup = {
  /**
   * Классы обёртки — она встаёт сразу после обёртки кнопки эмодзи.
   */
  wrapClass: string;

  /**
   * Классы внутреннего узла: он принимает клик и несёт подсказку.
   */
  innerClass: string;

  /**
   * Классы иконки в закрытом состоянии, вместе с `idleClasses`.
   */
  iconClass: string;

  /**
   * Атрибут `fill` иконки — для разметки, где цвет задаёт `color` (`currentColor`); без него
   * заливку задают классы.
   */
  iconFill?: string;

  /**
   * Классы цвета иконки при закрытом попапе.
   */
  idleClasses: string[];

  /**
   * Классы цвета иконки при открытом попапе — заменяют `idleClasses`, а не дополняют их.
   */
  openClasses: string[];

  /**
   * Где встаёт попап этой разметки.
   */
  anchor: ButtonAnchor;
};

export type Composer = {
  /**
   * Поле ввода (contenteditable).
   */
  editable: HTMLElement;

  /**
   * Строка инпута: [скрепка][текст][@][эмодзи][микрофон].
   */
  row: HTMLElement;

  /**
   * Обёртка кнопки эмодзи — кнопка стикеров встаёт сразу после неё.
   */
  emojiWrap: HTMLElement;

  /**
   * Кнопка «Отправить», найденная вместе с полем. null — не нашлась в разметке.
   */
  sendButton: HTMLElement | null;

  /**
   * Кнопка отмены редактирования, найденная вместе с полем. null — не нашлась в разметке.
   */
  cancelEditButton: HTMLElement | null;

  /**
   * Разметка amo, в которой поле найдено: черновик читается её признаком, кнопка стикеров
   * строится по ней.
   */
  markup: AmoMarkup;
};

/**
 * Срез `Composer`, который нужен отправке: поле ввода — для команды агенту и вставки, кнопки —
 * для проверок черновика и клика «Отправить». `Composer` подходит под него как есть.
 */
export type SendComposer = {
  /**
   * Поле ввода: его помечает команда агенту, в него идёт вставка на запасном пути.
   */
  editable: MarkableNode & Pick<HTMLElement, 'focus' | 'dispatchEvent'>;

  /**
   * Кнопка «Отправить», найденная вместе с полем: по её видимости черновик читают разметки, у
   * которых она смонтирована всегда. null — не нашлась. Нажимается кнопка из
   * `markup.sendButtonOf`, а не эта.
   */
  sendButton: (ShownNode & SendButton) | null;

  /**
   * Кнопка отмены редактирования, найденная вместе с полем: видна, пока идёт редактирование.
   * null — не нашлась.
   */
  cancelEditButton: ShownNode | null;

  /**
   * Разметка amo, в которой поле найдено: по ней читается черновик.
   */
  markup: ComposeMarkup;
};

/**
 * Чем задан размер места под стикер в ленте.
 *
 * `image` — загруженной картинкой: место amo сбрасывается в `auto`, картинка вписывается в лимит
 * сама; до загрузки размер не известен. `frame` — переменными `--media-w` / `--media-h`
 * контейнера: место встаёт в итоговый размер ещё в заглушке, картинка заполняет его.
 */
export type StickerSizing =
  | {
      /**
       * Размер задаёт загруженная картинка.
       */
      by: 'image';

      /**
       * Контейнер над картинкой стикера с inline-размером amo.
       */
      frame: string;

      /**
       * Картинка стикера.
       */
      image: string;
    }
  | {
      /**
       * Размер задают переменные контейнера.
       */
      by: 'frame';

      /**
       * Контейнер картинки стикера с переменными размера.
       */
      frame: string;
    };

/**
 * Цели стиля ленты в одной разметке amo — селекторы, которые `amoDomStyle.ts` превращает в CSS.
 * Каждый селектор уже ограничен своим сообщением amo stickers: правила не проверяют путь сами.
 */
export type MessageSelectors = {
  /**
   * Пузырь нашего сообщения: фон, тень и скругление снимаются.
   */
  bubble: string;

  /**
   * Хвост пузыря нашего сообщения.
   */
  tail: string;

  /**
   * Размытая подложка нашей картинки.
   */
  backdrop: string;

  /**
   * Строка имени автора над нашей картинкой.
   */
  author: string;

  /**
   * Наша картинка: вписывается без обрезки.
   */
  image: string;

  /**
   * Кнопка медиа стикера: её минимальный размер amo сбрасывается.
   */
  stickerButton: string;

  /**
   * Размер места под стикер.
   */
  stickerSizing: StickerSizing;

  /**
   * Слой amo со спиннером поверх места стикера — пока файл скачивается или отправляется: его
   * сплошная заливка снимается, спиннер остаётся.
   */
  stickerSpinnerLayer: string;

  /**
   * Плашка цитаты ответа нашей картинкой.
   */
  quote: string;

  /**
   * Плашка цитаты у стикера.
   */
  stickerQuote: string;

  /**
   * Плашка цитаты у GIF.
   */
  gifQuote: string;

  /**
   * Ряд сообщения-ответа нашей картинкой: контейнер для ширины плашки.
   */
  replyRow: string;

  /**
   * Обёртка панели действий при наведении у ответа нашей картинкой.
   */
  replyControls: string;

  /**
   * Признак исходящего на корне сообщения — приставка к селектору плашки.
   */
  outgoing: string;

  /**
   * Признак входящего под заголовком автора, в ряду которого есть аватар, — приставка к
   * селектору плашки.
   */
  withAvatar: string;
};

/**
 * Одна версия разметки amo: как найти поле ввода и чем стилизовать ленту. Разные версии не
 * пересекаются — узел одной не находится селекторами другой.
 */
export type AmoMarkup = ComposeMarkup & {
  /**
   * Поля ввода этой разметки в `root`; поле без строки или кнопки эмодзи пропускается.
   */
  findComposers: (root: ParentNode) => Composer[];

  /**
   * Кнопка стикеров у поля этой разметки.
   */
  button: ButtonMarkup;

  /**
   * Цели стиля ленты.
   */
  message: MessageSelectors;
};

/**
 * Вариант плашки цитаты стикера-ответа.
 */
export type QuoteLayout = {
  /**
   * Селектор плашек этого варианта.
   */
  selector: string;

  /**
   * Вид картинки: от него зависит, сколько места рядом с ней оставляет пузырь.
   */
  media: 'sticker' | 'gif';

  /**
   * Что ещё занимает ряд рядом с пузырём, px: зазор, слот чекбокса и, если есть, аватар.
   */
  reservePx: number;
};

/**
 * Место плашки рядом с картинкой.
 */
export type QuoteRoom = {
  /**
   * Свободное место рядом с картинкой — выражение для `calc()` в единицах ряда (`cqw`).
   */
  freeCalc: string;

  /**
   * Ширина ряда, px, уже которой плашка встаёт над картинкой.
   */
  narrowRowPx: number;
};
