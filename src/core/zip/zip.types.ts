/**
 * Вид ошибки архива. Перевод в текст для пользователя — у вызывающей стороны: `zip/` не знает ни
 * словаря, ни формата файла amo stickers.
 *
 * - `broken` — архив повреждён, обрезан, не zip или устроен так, как мы не читаем (zip64,
 *   многодисковый, неизвестный метод сжатия у читаемой записи);
 * - `tooLarge` — архив выходит за пределы zip32 или за предел числа записей вызывающей стороны.
 */
export type ZipErrorKind = 'broken' | 'tooLarge';

/**
 * Запись архива для упаковки.
 */
export type ZipWriteEntry = {
  /**
   * Путь внутри архива через `/`, без ведущего `/`. Пишется в UTF-8 с флагом бита 11.
   */
  name: string;

  /**
   * Содержимое записи; в архив попадает как есть, без сжатия.
   */
  data: Blob;
};

/**
 * Параметры упаковки.
 */
export type ZipWriteOptions = {
  /**
   * Время изменения записей, которое архиватор покажет у распакованных файлов. По умолчанию —
   * момент упаковки.
   */
  modified?: Date;

  /**
   * Колбэк на упаковку записи: число записей, уже упакованных в архив, — после CRC каждой записи.
   */
  onEntry?: (written: number) => void;
};

/**
 * Запись центрального каталога архива.
 */
export type ZipEntry = {
  /**
   * Путь записи внутри архива. Запись-папка оканчивается на `/`.
   */
  name: string;

  /**
   * Метод сжатия: 0 — без сжатия, 8 — deflate; другие не читаются.
   */
  method: number;

  /**
   * Флаги общего назначения из центрального каталога.
   */
  flags: number;

  /**
   * CRC-32 распакованных данных из центрального каталога.
   */
  crc32: number;

  /**
   * Размер данных записи в архиве.
   */
  compressedSize: number;

  /**
   * Размер распакованных данных.
   */
  uncompressedSize: number;

  /**
   * Смещение локального заголовка записи от начала архива.
   */
  localOffset: number;

  /**
   * Граница, до которой должны уместиться локальный заголовок и данные записи: начало следующей по
   * смещению записи или центрального каталога. Запись, чей заголовок делит смещение с другой, или
   * лежащая за началом каталога, получает границу не больше своего смещения — и не читается.
   */
  regionEnd: number;
};

/**
 * Центральный каталог архива: записи, на которые можно сослаться по имени.
 */
export type ZipDirectory = {
  /**
   * Записи по имени. Записей с опасными именами (`..`, `\`, абсолютный путь, буква диска) здесь
   * нет: сослаться на них нельзя.
   */
  entries: Map<string, ZipEntry>;
};

/**
 * Пределы чтения центрального каталога.
 */
export type ZipDirectoryLimits = {
  /**
   * Наибольшее число записей в архиве без служебных `__MACOSX/`; больше — ошибка `tooLarge`.
   */
  maxEntries: number;
};

/**
 * Параметры чтения записи.
 */
export type ZipEntryReadOptions = {
  /**
   * Наибольший размер распакованных данных; больше — ошибка `broken`. Распаковка обрывается, как
   * только выход его превысил.
   */
  maxBytes: number;

  /**
   * MIME-тип возвращаемого `Blob`. По умолчанию — пустой.
   */
  type?: string;
};

/**
 * Данные записи, сверенные с каталогом.
 */
export type ZipEntryContent = {
  /**
   * Данные записи; у метода 0 — срез архива без копии.
   */
  blob: Blob;

  /**
   * Те же данные в памяти: по ним посчитан CRC-32, и вызывающему не нужно читать запись второй раз.
   */
  bytes: Uint8Array<ArrayBuffer>;
};

/**
 * Прочитанные данные записи до сверки с каталогом.
 */
export type ZipEntryData = ZipEntryContent & {
  /**
   * CRC-32 прочитанных байтов.
   */
  crc: number;

  /**
   * Число прочитанных байтов.
   */
  size: number;
};
