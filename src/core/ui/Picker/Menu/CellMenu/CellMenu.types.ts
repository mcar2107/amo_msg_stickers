import type { SendItem } from '@core/db.types';
import type { MenuOpening } from '@ui/Menu';

/**
 * Что убирает пункт меню ячейки: стикер из библиотеки или элемент из недавних.
 */
export type CellRemoveKind = 'sticker' | 'recent';

/**
 * Удаление в меню: `kind` и `onRemove` задаются только вместе, поэтому тип связывает их, а не
 * держит независимо необязательными. Нет удаления — нет и пункта: у найденной GIF и ячейки
 * «Избранного» в меню «Предпросмотр» и пункт избранного.
 */
export type CellMenuRemove =
  | {
      /**
       * Что убирает пункт удаления.
       */
      kind: CellRemoveKind;

      /**
       * Колбэк на выбор пункта удаления: элемент ячейки убирается.
       */
      onRemove: () => void;
    }
  | {
      /**
       * Удаления нет: нет и `kind`.
       */
      kind?: undefined;

      /**
       * Удаления нет: нет и колбэка.
       */
      onRemove?: undefined;
    };

export type CellMenuProps = CellMenuRemove & {
  /**
   * Название меню на языке интерфейса: «Действия: стикер 😀».
   */
  label: string;

  /**
   * Элемент ячейки: по нему пункт избранного выбирает подпись «Добавить» или «Убрать».
   */
  favoriteItem: SendItem;

  /**
   * Где открыто меню и куда вернуть фокус.
   */
  opening: MenuOpening;

  /**
   * Колбэк на закрытие меню.
   */
  onClose: () => void;

  /**
   * Колбэк на выбор пункта «Предпросмотр» — после закрытия меню. Читает источник из
   * `opening.source` тот, кто открыл меню.
   */
  onPreview: () => void;

  /**
   * Колбэк на выбор пункта избранного — после закрытия меню: элемент ячейки добавляется в
   * избранное или убирается из него.
   */
  onFavoriteToggle: () => void;
};
