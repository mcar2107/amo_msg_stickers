import type { ImportCount } from '../PickerProvider/PickerProvider.types';

export type TelegramImportState = {
  /**
   * Ссылка на пак или его имя, как ввёл пользователь.
   */
  link: string;

  /**
   * В поле есть непробельный символ. Без него «Импорт» недоступен: пустой ввод — не
   * ошибка, а ещё не начатый.
   */
  hasLink: boolean;

  /**
   * Ошибка значения поля ссылки; `null` — ошибки нет.
   */
  fieldError: string | null;

  /**
   * Меняет введённую ссылку и снимает ошибку поля.
   */
  changeLink: (link: string) => void;

  /**
   * Идёт импорт: повторный запуск недоступен.
   */
  isImporting: boolean;

  /**
   * Ход импорта; `null` — импорт не идёт, полоса прогресса скрыта: после успеха и после
   * ошибки её нет.
   */
  progress: ImportCount | null;

  /**
   * Импортирует пак по введённой ссылке. Промис не отклоняется: ошибка уходит к полю ссылки
   * или, если поля не видно, в статус; по успеху открывается вкладка пака.
   */
  startImport: () => Promise<void>;
};
