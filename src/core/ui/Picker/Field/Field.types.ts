import type { ComponentChildren } from 'preact';

export type FieldProps = {
  /**
   * id поля: связывает с ним подпись, и из него выводятся id узлов описания.
   */
  id: string;

  /**
   * Постоянная подпись над полем — имя поля в дереве доступности.
   */
  label: ComponentChildren;

  /**
   * Элементы в строке подписи сразу после неё — кнопка рядом с подписью. Лежат вне `<label>`:
   * их имя не входит в имя поля.
   */
  labelAside?: ComponentChildren;

  /**
   * Текущее значение.
   */
  value: string;

  /**
   * Пример значения в пустом поле. Имя поля он не заменяет.
   */
  placeholder?: string;

  /**
   * Значение скрыто как пароль, рядом — кнопка «Показать» / «Скрыть»: ключи и токены.
   */
  isSecret?: boolean;

  /**
   * Ошибка значения под полем. Пока она есть, поле помечено недействительным.
   */
  error?: ComponentChildren;

  /**
   * Результат проверки значения под полем.
   */
  result?: ComponentChildren;

  /**
   * Тон результата проверки: `valid` — поле и результат зелёные, `invalid` — красные, и поле
   * помечено недействительным; `null` — без тона. Ошибка значения (`error`) важнее тона.
   */
  tone?: FieldTone | null;

  /**
   * Подсказка под полем: что вводить и где это взять.
   */
  hint?: ComponentChildren;

  /**
   * id описаний вне поля через пробел — они тоже читаются как описание поля.
   */
  describedBy?: string;

  /**
   * Колбэк на ввод: новое значение поля.
   */
  onInput: (value: string) => void;
};

/**
 * Тон результата проверки поля.
 */
export type FieldTone = 'valid' | 'invalid';
