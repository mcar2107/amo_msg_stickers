import type { ScheduleTimer } from '@core/hoverPopup.types';

/**
 * Нажатие, с которого может начаться удержание. Поля совпадают с полями `PointerEvent`,
 * жест не зависит от DOM.
 */
export type PressStart = {
  /**
   * Кнопка нажатия: `0` — основная кнопка мыши, касание и перо основного контакта.
   */
  button: number;

  /**
   * Вид указателя: `mouse`, `pen` или `touch`.
   */
  pointerType: string;

  /**
   * На нажатии зажат Ctrl: на macOS Ctrl+клик — правый клик, он открывает контекстное меню
   * и удержанием не считается.
   */
  isCtrlPressed: boolean;

  /**
   * Горизонтальная координата нажатия.
   */
  x: number;

  /**
   * Вертикальная координата нажатия.
   */
  y: number;
};

/**
 * Точка нажатия, от которой считается сдвиг указателя.
 */
export type PressOrigin = {
  /**
   * Горизонтальная координата.
   */
  x: number;

  /**
   * Вертикальная координата.
   */
  y: number;
};

/**
 * Параметры жеста удержания.
 */
export type PressGestureOptions = {
  /**
   * Удержание состоялось: основная кнопка не отпущена дольше `HOLD_DELAY_MS`, а указатель
   * не ушёл дальше `HOLD_SLOP_PX`.
   */
  onHold: () => void;

  /**
   * Планировщик таймеров; по умолчанию — `setTimeout` / `clearTimeout`.
   */
  schedule?: ScheduleTimer;
};

/**
 * Жест удержания кнопки без DOM: вызывающая сторона переводит события указателя в `start`,
 * `move` и `cancel`, жест решает, когда звать `onHold`.
 */
export type PressGesture = {
  /**
   * Нажатие. Удержание запускается только основной кнопкой мыши или пера; правая и средняя
   * кнопки и касание игнорируются. Новое нажатие отменяет незавершённое.
   */
  start: (press: PressStart) => void;

  /**
   * Указатель сдвинулся: дальше `HOLD_SLOP_PX` от точки нажатия — удержание отменяется.
   */
  move: (x: number, y: number) => void;

  /**
   * Отпускание, отмена жеста или уход указателя с ячейки: отсчёт останавливается. После
   * срабатывания `onHold` ничего не делает.
   */
  cancel: () => void;

  /**
   * Снятие таймера при размонтировании: `onHold` больше не вызывается.
   */
  dispose: () => void;
};
