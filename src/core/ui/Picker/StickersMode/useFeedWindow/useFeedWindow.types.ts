import type { RefObject } from 'preact';

import type { RowRange, StickerLayout } from '@ui/stickerLayout';
import type { FeedSticker } from '@ui/StickersMode/feedSections';

export type FeedWindow = {
  /**
   * Прокручиваемый элемент ленты.
   */
  scrollRef: RefObject<HTMLDivElement>;

  /**
   * Раскладка ленты; `null` — ширина ленты ещё не известна, рисовать нечего.
   */
  layout: StickerLayout<FeedSticker> | null;

  /**
   * Ряды раскладки, которые есть в документе: видимая область с запасом, а перед мгновенным
   * переходом к далёкому разделу — ещё и окно точки перехода. Диапазоны не пересекаются и идут по
   * возрастанию.
   */
  ranges: RowRange[];

  /**
   * Выбранный раздел: пока лента плавно едет по клику на вкладку — нажатый, иначе раздел, в
   * котором верх видимой области, а у ленты, прокрученной до конца, — последний; `null` — лента
   * пустая.
   */
  activeId: string | null;

  /**
   * Сообщает о прокрутке ленты: окно рядов пересчитывается не чаще кадра, а удержание нажатой
   * вкладки живёт, пока лента едет.
   */
  trackScroll: () => void;

  /**
   * Перечитывает прокрутку сразу — после того как её поставил код, а не пользователь.
   */
  syncScroll: () => void;
};

/**
 * Плавный переход ленты к разделу по клику на вкладку.
 */
export type FeedGlide = {
  /**
   * Раздел, к которому едет лента.
   */
  sectionId: string;

  /**
   * Прокрутка, к которой лента доезжает плавно, в пикселях.
   */
  target: number;

  /**
   * Прокрутка мгновенного перехода, который ещё не сделан: окно рядов в этой точке готовится;
   * `null` — перехода нет или он уже сделан.
   */
  jumpTo: number | null;
};
