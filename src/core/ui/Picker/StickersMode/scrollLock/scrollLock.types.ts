import type { ScheduleTimer } from '@core/hoverPopup.types';

export type ScrollLockOptions = {
  /**
   * Тишина прокрутки, после которой удержание снимается, мс: без событий прокрутки дольше этого
   * плавная прокрутка считается законченной.
   */
  quietMs: number;

  /**
   * Планировщик таймера тишины; по умолчанию — таймеры страницы.
   */
  schedule?: ScheduleTimer;

  /**
   * Колбэк на каждую смену удерживаемого раздела: новый раздел или `null`, когда удержание снято.
   */
  onChange: (sectionId: string | null) => void;
};

/**
 * Удержание выбранной вкладки на время плавной прокрутки ленты к разделу.
 */
export type ScrollLock = {
  /**
   * Удерживает `sectionId` выбранным и запускает таймер тишины заново.
   */
  lock: (sectionId: string) => void;

  /**
   * Событие прокрутки ленты: удержание, если оно есть, живёт ещё `quietMs`.
   */
  scroll: () => void;

  /**
   * Ввод пользователя на ленте: удержание снимается сразу.
   */
  interrupt: () => void;

  /**
   * Удерживаемый раздел; `null` — удержания нет, выбранная вкладка считается по прокрутке.
   */
  current: () => string | null;

  /**
   * Отменяет таймер; после этого удержание не меняется и `onChange` не зовётся.
   */
  dispose: () => void;
};
