import type { LocalSendItem, Pack, StickerRec } from '@core/db.types';
import type { CellNames } from '@ui/cellName';

/**
 * Стикер в ленте: одна ячейка сетки раздела.
 */
export type FeedSticker = {
  /**
   * Ключ ячейки, уникальный в разделе: id стикера у паков, ключ записи у недавних и избранного.
   */
  key: string;

  /**
   * Что отправляет ячейка.
   */
  item: LocalSendItem;

  /**
   * Запись стикера: блоб для картинки ячейки. Object URL создаётся только при показе ячейки.
   */
  sticker: StickerRec;

  /**
   * Ключ Object URL картинки: id стикера библиотеки — URL общий с ячейкой пака; `fav:<id>` у снимка
   * избранного, чей стикер удалён из библиотеки, — URL по id отдал бы отозванный удалением пака.
   */
  urlKey: string;

  /**
   * Имена кнопок ячейки на языке интерфейса.
   */
  name: CellNames;
};

/**
 * Раздел ленты стикеров.
 */
export type FeedSection = {
  /**
   * Идентификатор раздела: `pack.id` у паков, `recent` у недавних, `favorite` у избранного.
   */
  id: string;

  /**
   * Название раздела в заголовке и подсказке вкладки.
   */
  title: string;

  /**
   * Пак раздела — для обложки вкладки; `null` у недавних и избранного. Тот же объект, что в
   * списке паков пикера: вкладка перечитывает обложку при его смене.
   */
  pack: Pack | null;

  /**
   * Стикеры раздела в порядке показа.
   */
  items: FeedSticker[];

  /**
   * Раздел заканчивается плиткой «Создать стикер» — только «Мои стикеры».
   */
  hasCreateTile: boolean;

  /**
   * Подсказка вместо сетки, когда стикеров нет. Пустая у раздела с плиткой: её место занимает плитка.
   */
  hint: string;
};
