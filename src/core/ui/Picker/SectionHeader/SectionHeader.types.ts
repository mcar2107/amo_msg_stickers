export type SectionHeaderProps = {
  /**
   * Id раздела: `favorite`, `recent` или id пака. По нему выбирается действие заголовка.
   */
  sectionId: string;

  /**
   * Название раздела.
   */
  title: string;

  /**
   * Ссылка на пак для пункта «Копировать ссылку» в меню. `null` — у раздела её нет: избранное,
   * недавние, свои стикеры и пак без имени набора в Telegram.
   */
  link: string | null;

  /**
   * Верх ряда заголовка в ленте, в пикселях.
   */
  top: number;

  /**
   * Высота ряда заголовка, в пикселях.
   */
  height: number;

  /**
   * Колбэк на подтверждённое удаление пака раздела.
   */
  onPackDelete: (packId: string) => void;

  /**
   * Колбэк на подтверждённую очистку недавних стикеров.
   */
  onRecentClear: () => void;
};
