export type PackMenuButtonProps = {
  /**
   * Id пака — для пункта «Выгрузить пак».
   */
  packId: string;

  /**
   * Название пака — для подписи кнопки и меню.
   */
  title: string;

  /**
   * Ссылка на пак для пункта «Копировать ссылку». `null` — у пака ссылки нет, пункта нет.
   */
  link: string | null;

  /**
   * В паке есть стикеры: без них пункта «Выгрузить пак» нет — выгружать нечего.
   */
  hasStickers: boolean;

  /**
   * Колбэк на подтверждённое удаление пака. Без него пункта «Удалить пак» нет: пак своих стикеров не удаляется.
   */
  onDelete?: () => void;
};
