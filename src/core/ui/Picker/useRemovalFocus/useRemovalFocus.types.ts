import type { FocusTarget } from '@ui/removalFocus';

/**
 * Ожидание перечитанной ленты после удаления или правки.
 */
export type PendingFocus<T> = {
  /**
   * Цели фокуса по убыванию предпочтения.
   */
  targets: FocusTarget[];

  /**
   * Лента до удаления: цели применяются к первой ленте, отличной от неё.
   */
  feed: T;

  /**
   * Данные, которые меняет правка, в момент выбора пункта.
   */
  revision: unknown;

  /**
   * Ждать ленту из других данных правки, а не любую новую ленту: ленту меняет и чужая
   * перестройка — подгрузка выдачи, — и цели правки достались бы ей.
   */
  shouldWaitRevision: boolean;
};

/**
 * Запоминает цели фокуса перед удалением или правкой; фокус переходит на первую уцелевшую цель,
 * когда лента перечитана.
 */
type ExpectRemoval = (targets: FocusTarget[]) => void;

/**
 * Фокус после удаления или правки ленты.
 */
export type RemovalFocus = {
  /**
   * Цели применяются к первой новой ленте — перечитанной после удаления.
   */
  expectRemoval: ExpectRemoval;

  /**
   * Цели применяются к первой ленте из новых данных правки: чужая перестройка между выбором
   * пункта и ответом базы их не тратит.
   */
  expectEdit: ExpectRemoval;

  /**
   * Снимает запомненные цели: правка не применилась, и фокус не должен уйти по ним на следующей,
   * чужой перерисовке ленты.
   */
  cancelExpected: () => void;
};

/**
 * Элемент для фокуса по целям и перечитанной ленте; `null` — фокус не переводится.
 */
export type FocusElement<T> = (targets: FocusTarget[], feed: T) => HTMLElement | null;
