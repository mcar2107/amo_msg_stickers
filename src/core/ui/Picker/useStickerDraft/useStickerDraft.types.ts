import type { GifResult } from '../../../convert.types';

/**
 * Готовый стикер черновика и object URL его превью: URL живёт ровно столько, сколько
 * черновик.
 */
export type StickerDraft = {
  /**
   * GIF, который уйдёт в «Мои стикеры».
   */
  gif: GifResult;

  /**
   * Подпись, с которой нарисован этот GIF, а не текущее значение поля: поле могли
   * поправить после конвертации, и в записи стикера подпись должна совпасть с картинкой.
   * Пустая строка — GIF без подписи.
   */
  caption: string;

  /**
   * Object URL превью этого GIF.
   */
  url: string;
};

/**
 * Причина недоступности сохранения: `noFile` — файл не выбран, `converting` — стикер
 * собирается; `null` — пояснять нечего.
 */
export type SaveBlock = 'noFile' | 'converting' | null;

export type SaveBlockInput = {
  /**
   * Исходный файл выбран.
   */
  hasFile: boolean;

  /**
   * Стикер собирается: после выбора файла или правки подписи.
   */
  isConverting: boolean;
};

export type DraftConvertingInput = {
  /**
   * Исходный файл выбран.
   */
  hasFile: boolean;

  /**
   * Подпись, как её ввёл пользователь.
   */
  caption: string;

  /**
   * Подпись без пробелов по краям, по которой стикер собран или собирается.
   */
  drawnCaption: string;

  /**
   * GIF кодируется.
   */
  isEncoding: boolean;
};

export type StickerDraftState = {
  /**
   * Имя выбранного файла; `null` — файл ещё не выбран.
   */
  fileName: string | null;

  /**
   * Подпись, как её ввёл пользователь.
   */
  caption: string;

  /**
   * Object URL превью готового стикера; `null` — превью нет: файл не выбран или
   * конвертация не удалась.
   */
  previewUrl: string | null;

  /**
   * Стикер готов, не пересобирается и ещё не сохраняется: его можно сохранить.
   */
  isSavable: boolean;

  /**
   * Стикер собирается: после выбора файла или правки подписи, включая задержку ввода
   * подписи. Превью, если есть, — от прежней сборки.
   */
  isConverting: boolean;

  /**
   * Причина недоступности сохранения для текста рядом с кнопкой.
   */
  saveBlock: SaveBlock;

  /**
   * Выбирает исходный файл; `undefined` — выбор отменён, черновик не меняется.
   */
  pickFile: (file: File | undefined) => void;

  /**
   * Меняет подпись: стикер пересобирается через 500 мс после последнего ввода.
   */
  changeCaption: (caption: string) => void;

  /**
   * Сохраняет стикер в конец «Моих стикеров» и открывает этот пак. Промис не
   * отклоняется: ошибка уходит в статус.
   */
  save: () => Promise<void>;
};
