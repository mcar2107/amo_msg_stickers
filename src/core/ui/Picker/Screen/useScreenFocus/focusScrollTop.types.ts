/**
 * Отрезок элемента по вертикали в координатах прокручиваемого тела, от начала его содержимого.
 */
type BodySpan = {
  /**
   * Верх элемента, в пикселях.
   */
  top: number;

  /**
   * Высота элемента, в пикселях.
   */
  height: number;
};

export type FocusScrollInput = {
  /**
   * Группа, в которой лежит цель: заголовок и пояснение рядом с кнопкой объясняют, куда пришёл пользователь.
   */
  group: BodySpan;

  /**
   * Цель фокуса.
   */
  target: BodySpan;

  /**
   * Текущая прокрутка тела.
   */
  scrollTop: number;

  /**
   * Высота видимой области тела.
   */
  viewport: number;
};
