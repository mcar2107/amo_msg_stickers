import type { ComponentChildren } from 'preact';

export type ScreenProps = {
  /**
   * Заголовок экрана — и имя его области в дереве доступности.
   */
  title: string;

  /**
   * Содержимое футера экрана: главная кнопка и то, что стоит рядом с ней. Без него строки
   * футера нет, и тело тянется до низа панели.
   */
  footer?: ComponentChildren;

  /**
   * Содержимое тела делит его высоту, а не прокручивается: блок, которому разрешено сжиматься,
   * ужимается до свободного места. Без флага тело — обычный блок, и длинное содержимое
   * прокручивается целиком.
   */
  shouldFitBody?: boolean;

  /**
   * Прокручиваемое тело экрана.
   */
  children: ComponentChildren;
};
