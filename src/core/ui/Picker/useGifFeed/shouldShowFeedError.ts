import type { ShouldShowFeedErrorOptions } from './useGifFeed.types';

/**
 * Показывать ли ошибку загрузки ленты GIF в строке статуса. Пока открыт экран, лента под ним
 * не видна, а строка статуса принадлежит экрану: неверный ключ на «Настройках» перезагружает
 * ленту, и её ошибка перебила бы «Сохранено».
 *
 * Загрузка, начатая при открытом экране, молчит и тогда, когда ответ пришёл после его
 * закрытия: иначе исход зависел бы от того, успел ли ответ до «Назад», и ошибка стирала бы
 * «Сохранено», переехавшее в режим. Загрузки, начатые без экрана, показывают ошибку как обычно.
 *
 * @param options — последний ли это запрос, экран на старте загрузки и в момент ошибки
 * @returns нужно ли показать ошибку
 */
export const shouldShowFeedError = (options: ShouldShowFeedErrorOptions): boolean => {
  const { isLatest, startScreen, screen } = options;

  return isLatest && !startScreen && !screen;
};
