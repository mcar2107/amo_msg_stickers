/**
 * Второй и следующие клики двойного клика: `detail` — номер клика в серии, у нажатия с
 * клавиатуры он `0`. Кнопка футера меняется с «Импорт» на «Отменить» на месте, и второй клик
 * двойного клика попал бы в «Отменить» и оборвал только что начатый импорт.
 *
 * @param detail — `detail` события клика
 * @returns клик — повтор в серии, его нужно пропустить
 */
export const isRepeatClick = (detail: number): boolean => {
  return detail > 1;
};
