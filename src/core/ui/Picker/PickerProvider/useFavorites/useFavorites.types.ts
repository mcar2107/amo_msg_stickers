import type {
  FavoriteRec,
  LocalSendItem,
  RemoteSendItem,
  SendItem,
  StickerRec,
} from '../../../../db.types';

export type FavoritesContextValue = {
  /**
   * Записи избранного от новых к старым; `null` — ещё не прочитаны. После сбоя чтения — пустой список или прочитанный
   * раньше, а не `null`: сбой одного хранилища не прячет ленту.
   */
  favorites: FavoriteRec[] | null;

  /**
   * Ключи элементов избранного (`itemKey`): по ним пункт меню любой ячейки узнаёт, в избранном ли её элемент.
   */
  keys: Set<string>;

  /**
   * Перечитывает избранное из базы — на каждое открытие попапа: правка из другой вкладки видна при следующем открытии.
   * Отклоняется ошибкой чтения, состояние при этом — пустое или прежнее избранное.
   */
  refreshFavorites: () => Promise<void>;

  /**
   * Добавляет элемент в избранное или убирает из него — по тому, есть ли он там сейчас, — и показывает итог в статусе.
   * Сбой записи — ошибка в статусе, избранное не меняется. Промис не отклоняется.
   *
   * @returns `true` — изменение записано и применено
   */
  toggleFavorite: (item: SendItem, sticker?: StickerRec) => Promise<boolean>;
};

export type FavoritesOptions = {
  /**
   * Показывает итог правки в статусе.
   */
  showStatus: (text: string) => void;

  /**
   * Показывает ошибку записи в статусе.
   */
  showError: (text: string) => void;
};

/**
 * Правка избранного из ячейки ленты: ряды и сетки отдают её режиму, а тот решает фокус и место ленты и зовёт
 * `toggleFavorite`.
 */
export type FavoriteToggle = {
  /**
   * Раздел ленты, в котором выбран пункт.
   */
  sectionId: string;

  /**
   * Ключ ячейки в разделе: по нему с id раздела находится её кнопка.
   */
  cellKey: string;
} & (
  | {
      /**
       * Стикер из библиотеки или из избранного.
       */
      item: LocalSendItem;

      /**
       * Запись стикера ячейки: снимок для избранного, чтобы стикер жил там и после удаления пака.
       */
      sticker: StickerRec;
    }
  | {
      /**
       * GIF из поиска, недавних или избранного.
       */
      item: RemoteSendItem;

      /**
       * У GIF снимка нет: её данных хватает для показа и отправки.
       */
      sticker?: undefined;
    }
);
