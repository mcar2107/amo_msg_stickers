import type { ComponentChildren } from 'preact';

import type { Pack, SendItem } from '../../../db.types';
import type { Host, Settings } from '../../../host.types';
import type { HoldReason, OpenedBy, PopupHolds } from '../../../hoverPopup.types';
import type {
  AddSegment,
  PickerScreen,
  PickerViewValue,
  SectionMotion,
} from '../usePickerView/usePickerView.types';

import type { PackCard } from './packCardView/packCardView.types';

export type PickerStatus = {
  /**
   * Текст строки статуса.
   */
  text: string;

  /**
   * Статус — ошибка: показывается цветом ошибки.
   */
  isError: boolean;
};

export type RefreshPacksOptions = {
  /**
   * Порядок паков считается заново по использованию — так на открытии попапа. Без флага паки встают по порядку,
   * показанному с открытия, а новые паки — перед паками Telegram: порядок открытого попапа не меняется.
   */
  isReorder?: boolean;
};

export type PickerContextValue = {
  /**
   * Окружение: сеть и настройки расширения или userscript.
   */
  env: Host;

  /**
   * Настройки на момент последней загрузки.
   */
  settings: Settings;

  /**
   * Перечитывает настройки из окружения при открытии пикера.
   */
  refreshSettings: () => Promise<void>;

  /**
   * Записывает изменённые поля настроек в окружение и применяет их без перезагрузки страницы.
   * Удачная запись статуса не показывает: значение сохраняется само, а принято ли оно, говорит
   * проверка у поля. Записи идут по одной в порядке вызова, а перечитывание настроек ждёт
   * начатую запись. Промис не отклоняется: ошибка уходит в статус.
   *
   * @returns `true` — поля записаны
   */
  saveSettings: (next: Partial<Settings>) => Promise<boolean>;

  /**
   * Паки стикеров в порядке вкладок: свой пак, затем паки Telegram по использованию на момент открытия попапа.
   */
  packs: Pack[];

  /**
   * Перечитывает паки из базы — на открытии попапа с пересчётом порядка, после импорта, создания или удаления — без
   * него.
   */
  refreshPacks: (options?: RefreshPacksOptions) => Promise<void>;

  /**
   * Текущий статус; `null` — строка статуса скрыта.
   */
  status: PickerStatus | null;

  /**
   * Показывает информационный статус.
   */
  showStatus: (text: string) => void;

  /**
   * Показывает статус ошибки.
   */
  showError: (text: string) => void;

  /**
   * Скрывает строку статуса.
   */
  clearStatus: () => void;

  /**
   * Отправляет стикер или GIF: статус «Отправляю…», при успехе — закрытие пикера и отметка
   * использования пака `packId`, если он передан, при ошибке — её текст в статусе. Промис не
   * отклоняется и завершается вместе с отправкой и отметкой.
   */
  send: (item: SendItem, packId?: string) => Promise<void>;

  /**
   * Object URL блоба стикера: для одного id один и тот же URL, пока пикер открыт. При
   * закрытии URL отзываются, после открытия `urlOf` создаёт новые.
   */
  urlOf: (id: string, blob: Blob) => string;

  /**
   * Отзывает URL удалённого стикера.
   */
  dropUrl: (id: string) => void;

  /**
   * Импорт пака из Telegram: его ход переживает уход с вкладки «Добавить стикеры».
   */
  packImport: PackImportState;

  /**
   * Чем открыт пикер последний раз: наведением фокус из поля сообщения не уводится.
   */
  openedBy: OpenedBy;

  /**
   * Включает или снимает причину удержания пикера: удержанный пикер не закрывается уходом
   * курсора. Ссылка стабильна между рендерами.
   */
  setHold: (reason: HoldReason, isActive: boolean) => void;
};

export type PackImportState = {
  /**
   * Ссылка на пак или его имя, как ввёл пользователь. Переживает закрытие экрана и смену
   * сегмента, после успешного импорта — пустая.
   */
  link: string;

  /**
   * Ошибка значения поля ссылки: ссылка без имени пака, ошибка импорта, завершившегося на
   * открытом сегменте «Telegram», или ответ Telegram, что пака из поля нет; `null` — ошибки нет.
   * Правка ссылки снимает ошибку импорта, а «пак не найден» держится, пока в поле то же имя.
   */
  fieldError: string | null;

  /**
   * Telegram ответил, что пака из поля нет: «Импорт» недоступна, пока ссылку не исправят.
   */
  isPackMissing: boolean;

  /**
   * Карточка пака под полем: во время импорта — импортируемый пак и ход, иначе превью пака из
   * поля; `null` — карточки нет.
   */
  card: PackCard | null;

  /**
   * Меняет введённую ссылку и снимает ошибку поля.
   */
  changeLink: (link: string) => void;

  /**
   * Идёт импорт: повторный запуск недоступен, в том числе после возврата на вкладку.
   */
  isImporting: boolean;

  /**
   * Импортирует пак по введённой ссылке; пока идёт импорт, вызов ничего не делает. Ссылка без
   * имени пака — ошибка поля без запроса. Промис не отклоняется: ошибка уходит к полю или в
   * статус, по успеху открывается вкладка пака.
   */
  importPack: () => Promise<void>;

  /**
   * Отменяет идущий импорт: библиотека откатывается к состоянию до него, в статусе «Импорт
   * отменён». Без идущего импорта ничего не делает.
   */
  cancelImport: () => void;
};

export type PackImportOptions = {
  /**
   * Окружение: сеть для Bot API и загрузки файлов.
   */
  env: Host;

  /**
   * Настройки с токеном Telegram-бота.
   */
  settings: Settings;

  /**
   * Открытый экран поверх режима: к паку лента прокручивается, только если по завершении
   * открыт экран «Добавить стикеры».
   */
  screen: PickerScreen | null;

  /**
   * Выбранный сегмент экрана «Добавить стикеры»: ошибка импорта — у поля ссылки, только если
   * по завершении открыт сегмент «Telegram».
   */
  addSegment: AddSegment;

  /**
   * Паки библиотеки: по ним карточка говорит, что импорт обновит пак, уже лежащий в ней.
   */
  packs: Pack[];

  /**
   * Перечитывает паки: вкладка пака появляется после первого стикера и по завершении.
   */
  refreshPacks: () => Promise<void>;

  /**
   * Показывает ход импорта и итог в статусе.
   */
  showStatus: (text: string) => void;

  /**
   * Показывает ошибку импорта в статусе.
   */
  showError: (text: string) => void;

  /**
   * Скрывает строку статуса: ошибку у поля статус не дублирует.
   */
  clearStatus: () => void;

  /**
   * Открывает раздел импортированного пака в ленте стикеров.
   */
  scrollToSection: (sectionId: string, motion: SectionMotion) => void;
};

