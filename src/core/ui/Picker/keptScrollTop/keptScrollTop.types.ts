/**
 * Место ячейки ленты по вертикали.
 */
export type CellPosition = {
  /**
   * id кнопки ячейки: одинаковый у ячейки в раскладках до и после правки.
   */
  id: string;

  /**
   * Верх ячейки от начала ленты, в пикселях.
   */
  top: number;

  /**
   * Высота ячейки в пикселях.
   */
  height: number;
};

export type KeptScrollInput = {
  /**
   * Ячейки прежней раскладки в порядке ленты.
   */
  prev: CellPosition[];

  /**
   * Верхи ячеек новой раскладки по id.
   */
  next: ReadonlyMap<string, number>;

  /**
   * Прокрутка ленты при прежней раскладке.
   */
  scrollTop: number;
};

/**
 * Ячейка ленты стикеров: месту ячейки нужен только её ключ в разделе.
 */
export type KeyedCell = {
  /**
   * Ключ ячейки в разделе.
   */
  key: string;
};
