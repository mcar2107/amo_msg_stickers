import type { CellPosition } from '../keptScrollTop.types';

/**
 * Прокручиваемый элемент ленты: метке нужна только его прокрутка.
 */
export type ScrollElement = Pick<HTMLElement, 'scrollTop'>;

/**
 * Метка ожидания правки: раскладка и прокрутка ленты в момент правки.
 */
export type KeptMark = {
  /**
   * Ячейки раскладки, показанной в момент правки.
   */
  cells: CellPosition[];

  /**
   * Прокрутка ленты в момент правки.
   */
  scrollTop: number;
};

/**
 * Удержание места ленты на время правки избранного: режим ставит и снимает метку, а лента, где
 * живёт раскладка, сообщает о каждой новой раскладке и получает прокрутку для неё.
 */
export type KeptScroll = {
  /**
   * Ставит метку по последней показанной раскладке: следующая новая раскладка получит прокрутку,
   * при которой видимая часть ленты остаётся на месте. Раскладки ещё не было — метки нет.
   */
  keep: () => void;

  /**
   * Снимает метку: правка не применилась или попап закрылся, и следующая смена раскладки ленту не
   * двигает.
   */
  drop: () => void;

  /**
   * Сообщает о показанной раскладке и снимает метку, если раскладка с момента метки сменилась.
   *
   * @param cells — ячейки показанной раскладки
   * @param element — прокручиваемый элемент ленты
   * @returns прокрутка для этой раскладки; `null` — ставить нечего
   */
  settle: (cells: CellPosition[], element: ScrollElement) => number | null;
};
