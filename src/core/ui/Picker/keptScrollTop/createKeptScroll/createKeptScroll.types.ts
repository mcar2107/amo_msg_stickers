import type { CellPosition } from '../keptScrollTop.types';

/**
 * Прокручиваемый элемент ленты: метке нужна только его прокрутка.
 */
export type ScrollElement = Pick<HTMLElement, 'scrollTop'>;

/**
 * Метка ожидания правки: раскладка и прокрутка ленты, от которых встанет раскладка правки.
 */
export type KeptMark<R> = {
  /**
   * Ячейки раскладки, показанной перед правкой.
   */
  cells: CellPosition[];

  /**
   * Прокрутка ленты при этой раскладке.
   */
  scrollTop: number;

  /**
   * Данные, которые меняет правка, в момент метки: раскладка из других данных — раскладка правки.
   */
  revision: R;
};

/**
 * Удержание места ленты без привязки к рендеру: данные, которые меняет правка, передаются в каждый
 * вызов.
 */
export type KeptScrollControl<R> = {
  /**
   * Ставит метку по последней показанной раскладке: раскладка правки получит прокрутку, при
   * которой видимая часть ленты остаётся на месте. Раскладки ещё не было — метки нет.
   *
   * @param revision — данные, которые меняет правка, до неё
   */
  keep: (revision: R) => void;

  /**
   * Снимает метку: правка не применилась или попап закрылся, и следующая смена раскладки ленту не
   * двигает.
   */
  drop: () => void;

  /**
   * Сообщает о показанной раскладке. Раскладка из тех же данных, что в момент метки, метку
   * переносит на себя, из других — расходует.
   *
   * @param cells — ячейки показанной раскладки
   * @param element — прокручиваемый элемент ленты
   * @param revision — данные, из которых собрана раскладка
   * @returns прокрутка для этой раскладки; `null` — ставить нечего
   */
  settle: (cells: CellPosition[], element: ScrollElement, revision: R) => number | null;
};

/**
 * Удержание места ленты на время правки избранного, привязанное к данным текущего рендера: режим
 * ставит и снимает метку, а лента, где живёт раскладка, сообщает о каждой новой раскладке и
 * получает прокрутку для неё.
 */
export type KeptScroll = {
  /**
   * Ставит метку по последней показанной раскладке и данным рендера, из которого выбран пункт.
   */
  keep: () => void;

  /**
   * Снимает метку: правка не применилась или попап закрылся.
   */
  drop: () => void;

  /**
   * Сообщает о показанной раскладке рендера.
   *
   * @param cells — ячейки показанной раскладки
   * @param element — прокручиваемый элемент ленты
   * @returns прокрутка для этой раскладки; `null` — ставить нечего
   */
  settle: (cells: CellPosition[], element: ScrollElement) => number | null;
};
