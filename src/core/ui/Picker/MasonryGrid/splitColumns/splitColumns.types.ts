/**
 * Элемент ленты с известными размерами — по ним считается высота в колонке.
 */
export type SizedItem = {
  /**
   * Ширина в пикселях, больше нуля.
   */
  width: number;

  /**
   * Высота в пикселях, больше нуля.
   */
  height: number;
};

/**
 * Раздел ленты на входе раскладки.
 */
export type MasonrySection<T> = {
  /**
   * Идентификатор раздела, например `'recent'` или `'trends'`.
   */
  id: string;

  /**
   * Элементы раздела в порядке выдачи.
   */
  items: T[];

  /**
   * Есть ли у раздела строка заголовка над колонками.
   */
  hasHeader?: boolean;

  /**
   * Сколько заглушек положить в конец каждой колонки раздела: выдача или её следующая страница ещё грузится.
   */
  skeletons?: number;
};

/**
 * Геометрия колонок ленты в пикселях.
 */
export type ColumnGeometry = {
  /**
   * Число колонок, больше нуля.
   */
  count: number;

  /**
   * Ширина колонки в пикселях.
   */
  width: number;

  /**
   * Зазор между колонками и между ячейками в колонке, в пикселях.
   */
  gap: number;
};

/**
 * Место плитки в ленте.
 */
type TileBox = {
  /**
   * Раздел, которому принадлежит плитка.
   */
  sectionId: string;

  /**
   * Номер колонки слева. У заголовка — 0: он во всю ширину ленты.
   */
  column: number;

  /**
   * Верх плитки от начала ленты, в пикселях.
   */
  top: number;

  /**
   * Высота плитки в пикселях.
   */
  height: number;
};

/**
 * Плитка элемента выдачи.
 */
export type ItemTile<T> = TileBox & {
  /**
   * Вид плитки.
   */
  kind: 'item';

  /**
   * Элемент выдачи.
   */
  item: T;
};

/**
 * Плитка-заглушка загружающейся выдачи.
 */
type SkeletonTile = TileBox & {
  /**
   * Вид плитки.
   */
  kind: 'skeleton';

  /**
   * Номер заглушки в разделе — для ключа рендера.
   */
  index: number;
};

/**
 * Строка заголовка раздела во всю ширину ленты.
 */
type HeaderTile = TileBox & {
  /**
   * Вид плитки.
   */
  kind: 'header';
};

/**
 * Плитка ленты с позицией в пикселях.
 */
export type MasonryTile<T> = ItemTile<T> | SkeletonTile | HeaderTile;

/**
 * Раскладка ленты по колонкам.
 */
export type MasonryLayout<T> = {
  /**
   * Плитки в порядке выдачи: по разделам, в разделе — заголовок, элементы, затем заглушки.
   */
  tiles: MasonryTile<T>[];

  /**
   * Высота ленты в пикселях — низ самой длинной колонки.
   */
  total: number;
};
