/**
 * Кадр плана: какой момент источника захватить и сколько его показывать.
 */
export type FramePlanItem = {
  /**
   * Позиция кадра в источнике: секунды для видео, номер кадра для `.tgs` и `ImageDecoder`.
   */
  position: number;

  /**
   * Длительность показа кадра в мс; 0 — статичная картинка.
   */
  delayMs: number;
};

/**
 * Контекст, в который источник рисует кадр. Уже, чем `CanvasRenderingContext2D`:
 * источнику нужно только стереть холст и нарисовать кадр.
 */
type FrameTarget = Pick<CanvasRenderingContext2D, 'clearRect' | 'drawImage'>;

/**
 * Открытый источник кадров: кадры рисуются по запросу, а не хранятся, поэтому любой проход
 * (пробный, полный, повторный в меньшем размере) идёт по источнику, а не по прошлым кадрам.
 */
export type FrameSource = {
  /**
   * Ширина источника, вписанная в `maxSide`, в пикселях.
   */
  width: number;

  /**
   * Высота источника, вписанная в `maxSide`, в пикселях.
   */
  height: number;

  /**
   * Кадры в порядке показа, уже обрезанные до 4 с и 100 кадров.
   */
  plan: FramePlanItem[];

  /**
   * Рисует кадр `index` плана поверх стёртого холста в размере `width` × `height`.
   * Индекс вне плана — `RangeError`.
   */
  draw: (index: number, ctx: FrameTarget, width: number, height: number) => Promise<void>;

  /**
   * Освобождает ресурсы источника. Зовётся один раз при любом исходе конвертации.
   */
  dispose: () => void;
};
