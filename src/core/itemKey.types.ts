/**
 * Недавние, разделённые лимитом вида.
 */
export type NewestByKind<T> = {
  /**
   * Не больше `RECENT_LIMIT` самых поздних каждого вида, от новых к старым.
   */
  kept: T[];

  /**
   * Вытесненные лимитом своего вида, от новых к старым.
   */
  overflow: T[];
};

/**
 * Элемент недавних с временем отправки: запись базы или элемент файла.
 */
export type TimedRecent = {
  /**
   * Время последней отправки (мс).
   */
  ts: number;
};
