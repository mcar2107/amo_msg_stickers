/**
 * Чем открыт попап: наведение открывает его до ухода курсора, клик — закреплённым.
 */
export type OpenedBy = 'hover' | 'click';

/**
 * Планировщик таймера: запускает колбэк через `ms` и возвращает отмену. Отмена после
 * срабатывания ничего не делает.
 */
export type ScheduleTimer = (callback: () => void, ms: number) => () => void;

/**
 * Параметры контроллера попапа. `T` — кнопка, у которой попап открывается: на странице
 * может быть несколько полей ввода, а попап один.
 */
export type HoverPopupOptions<T> = {
  /**
   * Задержка открытия после наведения, мс: курсор, который прошёл кнопку быстрее, попап не
   * открывает.
   */
  openDelay: number;

  /**
   * Задержка закрытия после ухода курсора, мс: возврат до её конца отменяет закрытие.
   */
  closeDelay: number;

  /**
   * Колбэк на открытие попапа — наведением или кликом — у кнопки `target`.
   */
  onOpen: (openedBy: OpenedBy, target: T) => void;

  /**
   * Колбэк на закрытие попапа: один раз на каждое закрытие открытого.
   */
  onClose: () => void;

  /**
   * Удерживает ли что-то попап открытым: спрашивается в момент срабатывания таймера
   * закрытия. `true` — уход курсора попап не закрывает.
   */
  isHeld: () => boolean;

  /**
   * Уходит ли закрытый попап анимацией закрытия: возврат курсора в это время открывает его
   * сразу, без задержки открытия, — иначе панель успела бы скрыться и появиться заново.
   * Спрашивается о кнопке, на которую вернулся курсор. По умолчанию — нет.
   */
  isLeaving?: (target: T) => boolean;

  /**
   * Планировщик таймеров; по умолчанию — `setTimeout` / `clearTimeout`.
   */
  schedule?: ScheduleTimer;
};

export type HoverPopup<T> = {
  /**
   * Курсор вошёл на кнопку `target` или её попап. Открытый наведением у другой кнопки
   * попап закрывается сразу, закреплённый у другой кнопки — не замечает наведения.
   */
  enter: (target: T) => void;

  /**
   * Курсор ушёл с кнопки и попапа или за окно.
   */
  leave: () => void;

  /**
   * Клик по кнопке `target`: закрытый попап открывает закреплённым, открытый наведением —
   * закрепляет, закреплённый — закрывает. Попап, открытый у другой кнопки, закрывается там и
   * открывается закреплённым у `target`.
   */
  click: (target: T) => void;

  /**
   * Снято последнее удержание: попап, открытый наведением, при курсоре снаружи закрывается
   * после обычной задержки закрытия, а не висит до следующего входа и ухода курсора.
   */
  release: () => void;

  /**
   * Закрывает попап сразу и отменяет таймеры — клик вне попапа, Escape, закрытие изнутри.
   * Удержание не мешает.
   */
  dismiss: () => void;

  /**
   * Открыт ли попап.
   */
  readonly isOpen: boolean;
};

/**
 * Причина удержания попапа: фокус в текстовом поле панели, открытый системный диалог
 * выбора файла, идущий импорт пака, идущая конвертация стикера, открытый экран «Добавить
 * стикеры» или «Настройки», открытый предпросмотр.
 */
export type HoldReason =
  'field' | 'fileDialog' | 'import' | 'conversion' | 'screen' | 'preview';

export type PopupHolds = {
  /**
   * Включает или снимает причину удержания; повторная запись той же причины не копится.
   */
  set: (reason: HoldReason, isActive: boolean) => void;

  /**
   * Жива ли хоть одна причина удержания.
   */
  isHeld: () => boolean;

  /**
   * Снимает причины, привязанные к DOM панели, — фокус в поле, диалог файла и открытый
   * предпросмотр: скрытая панель не обязана прислать `focusout`, а без снятия удержание
   * пережило бы закрытие. Импорт, конвертация и черновик живут дальше и остаются.
   */
  releasePanel: () => void;
};

/**
 * Фаза панели: открыта, уходит анимацией закрытия (видна, но не принимает курсор) или
 * скрыта.
 */
export type PanelPhase = 'open' | 'closing' | 'closed';

export type PanelPhaseOptions = {
  /**
   * Длительность ухода, мс: столько панель остаётся в фазе `closing`.
   */
  closeDuration: number;

  /**
   * Колбэк на каждую смену фазы.
   */
  onChange: (phase: PanelPhase) => void;

  /**
   * Планировщик таймеров; по умолчанию — `setTimeout` / `clearTimeout`.
   */
  schedule?: ScheduleTimer;
};

export type PanelPhaseState = {
  /**
   * Текущая фаза.
   */
  readonly phase: PanelPhase;

  /**
   * Показывает панель; во время ухода отменяет скрытие. Открытую не трогает.
   */
  show: () => void;

  /**
   * Начинает уход открытой панели; уходящую и скрытую не трогает.
   */
  hide: () => void;
};
