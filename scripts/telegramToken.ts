/**
 * Токен Telegram-бота для встраивания в сборку. Только стираемый синтаксис TS и без
 * рантайм-импортов: `build.mjs` импортирует модуль напрямую, а Node снимает типы сам,
 * без сборки.
 */

/**
 * Форма токена Bot API — `<id бота>:<секрет>`. Проверка ловит не тот секрет или
 * обрезанную вставку до сборки, а не после релиза с нерабочим импортом.
 */
const TOKEN_PATTERN = /^\d+:[\w-]+$/;

/**
 * Значение переменной окружения → токен для `define`. Пробелы и переводы строки по краям
 * снимаются: секрет часто вставляют с концом строки.
 *
 * @param value — значение `TELEGRAM_BOT_TOKEN`, `undefined` — переменная не задана
 * @returns токен; пустая строка — сборка без встроенного токена
 * @throws {Error} значение не похоже на токен бота. Самого значения в тексте нет: он
 * попадает в лог сборки CI
 */
export const readTelegramToken = (value: string | undefined): string => {
  const token = (value || '').trim();

  if (!token) {
    return '';
  }

  if (!TOKEN_PATTERN.test(token)) {
    throw new Error(
      'TELEGRAM_BOT_TOKEN: неверный формат, ожидается <цифры>:<строка> из @BotFather'
    );
  }

  return token;
};
