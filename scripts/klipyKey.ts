/**
 * Ключ KLIPY для встраивания в сборку. Только стираемый синтаксис TS и без
 * рантайм-импортов: `build.mjs` импортирует модуль напрямую, а Node снимает типы сам,
 * без сборки.
 */

/**
 * Формат ключа KLIPY не опубликован, поэтому проверка мягкая: ловит пробел, кавычку или
 * перевод строки внутри вставки, а не длину и алфавит — строгая уронила бы релиз на
 * продовом ключе другого вида.
 */
const KEY_PATTERN = /^[\w-]+$/;

/**
 * Значение переменной окружения → ключ для `define`. Пробелы и переводы строки по краям
 * снимаются: секрет часто вставляют с концом строки.
 *
 * @param value — значение `KLIPY_API_KEY`, `undefined` — переменная не задана
 * @returns ключ; пустая строка — сборка без встроенного ключа
 * @throws {Error} в значении есть символы вне `[A-Za-z0-9_-]`. Самого значения в тексте
 * нет: он попадает в лог сборки CI
 */
export const readKlipyKey = (value: string | undefined): string => {
  const key = (value || '').trim();

  if (!key) {
    return '';
  }

  if (!KEY_PATTERN.test(key)) {
    throw new Error(
      'KLIPY_API_KEY: неверный формат, ожидаются только буквы, цифры, _ и -'
    );
  }

  return key;
};
